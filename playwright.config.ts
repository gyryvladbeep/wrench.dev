import { defineConfig, devices } from "@playwright/test";

/**
 * Playwright Configuration
 * ========================
 * Это центральный файл настроек для всех тестов.
 * Документация: https://playwright.dev/docs/test-configuration
 */
export default defineConfig({
  // Где лежат файлы тестов
  testDir: "./tests",

  // Запускать тесты параллельно — ускоряет прогон
  fullyParallel: true,

  // На CI (GitHub Actions) — падать если кто-то забыл test.only()
  forbidOnly: !!process.env.CI,

  // Количество повторных попыток при падении теста (полезно для нестабильных/flaky тестов)
  retries: process.env.CI ? 2 : 1,

  // Сколько тестов запускать одновременно.
  //
  // УРОК: почему тут не оставлено "undefined" (авто = все ядра процессора)
  // ─────────────────────────────────────────────────────────────────────
  // В режиме разработки (next dev) страницы компилируются "на лету" при
  // первом заходе. Если открыть сразу 8 браузеров на разные страницы —
  // сервер может не успеть скомпилировать всё вовремя, и тесты падают
  // по таймауту НЕ из-за бага в приложении, а из-за перегрузки сервера.
  // Ограничиваем до 4 воркеров — компромисс между скоростью и стабильностью.
  workers: process.env.CI ? 1 : 4,

  // Максимальное время на один тест целиком (по умолчанию 30 секунд —
  // маловато для медленного dev-сервера при первом заходе на страницу)
  timeout: 45_000,

  // Формат отчёта — HTML отчёт открывается в браузере после прогона
  reporter: [["html", { open: "never" }], ["list"]],

  use: {
    // Базовый URL — не нужно писать полный адрес в каждом тесте
    baseURL: process.env.BASE_URL || "http://localhost:3000",

    // Скриншот делается только если тест упал — экономит место
    screenshot: "only-on-failure",

    // Видео записывается только при первой повторной попытке после падения
    video: "retain-on-failure",

    // Трейс (полная запись действий) для отладки упавших тестов
    trace: "on-first-retry",

    // Сколько ждать переход на страницу / ответ сервера.
    // Увеличено из-за медленной компиляции dev-сервера при первом заходе.
    navigationTimeout: 30_000,

    // Сколько ждать одно действие (клик, ввод текста)
    actionTimeout: 15_000,
  },

  // В каких браузерах гоняем тесты
  projects: [
    {
      name: "chromium",
      use: { ...devices["Desktop Chrome"] },
    },
    // Раскомментируй когда захочешь тестировать в других браузерах:
    // {
    //   name: "firefox",
    //   use: { ...devices["Desktop Firefox"] },
    // },
    // {
    //   name: "mobile-chrome",
    //   use: { ...devices["Pixel 5"] },
    // },
  ],

  // Автоматически запускать сервер перед тестами.
  //
  // УРОК: почему команда разная для CI и для локальной разработки
  // ─────────────────────────────────────────────────────────────
  // Локально (на твоём компьютере) удобнее "npm run dev" — видишь
  // изменения сразу, без пересборки.
  //
  // На CI (GitHub Actions) мы уже собрали проект командой "npm run build"
  // ДО тестов (см. .github/workflows/playwright.yml) — значит там нужно
  // просто запустить готовую сборку через "npm run start". Она быстрее
  // и стабильнее, а именно стабильность важна на CI, где тест либо
  // проходит, либо нет — без права на "подожди, сервер ещё компилируется".
  webServer: {
    command: process.env.CI ? "npm run start" : "npm run dev",
    url: "http://localhost:3000",
    reuseExistingServer: !process.env.CI,
    timeout: 120_000,
  },
});