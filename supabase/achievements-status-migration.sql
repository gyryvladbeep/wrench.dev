-- Достижения как статус (2026-09-17)
-- ═══════════════════════════════════════════════════════════════════
-- achievements уже существует (supabase/profile-schema.sql, owner-only
-- RLS, UNIQUE(user_id, badge_id)), но до сих пор нигде не использовалась
-- — lib/achievements.ts всегда была чисто "живой" функцией, ничего не
-- писавшей в БД (см. старый комментарий в PublicProfileView.tsx). Из-за
-- этого бейджи, завязанные на current_streak, пропадали с профиля при
-- сбросе стрика, даже если он держался месяц. Начиная с этой миграции
-- app/[locale]/profile/page.tsx один раз ЗАПИСЫВАЕТ каждый новый
-- заработанный бейдж сюда (upsert, ON CONFLICT DO NOTHING — уже
-- обеспечивается существующим UNIQUE) и дальше показывает объединение
-- живого пересчёта с уже когда-либо записанными id.
--
-- Новой публичной SELECT-политики на achievements здесь НЕТ и
-- специально не нужно: публичный профиль (/u/[username]) не показывает
-- список "когда-либо заработанных" бейджей чужого пользователя целиком
-- (это была бы отдельная утечка активности за пределами того, что и так
-- уже публично видно через user_streaks) — он показывает только ОДИН
-- бейдж, который владелец сам явно выбрал как статус, через новую
-- колонку ниже на profiles. profiles уже имеет публичную SELECT-политику
-- profiles_select_public (supabase/profile-public-migration.sql,
-- is_public = true) — новая колонка автоматически попадает под неё же,
-- без отдельной политики.
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS equipped_badge_id text;

COMMENT ON COLUMN profiles.equipped_badge_id IS
  'id бейджа из lib/achievements.ts BADGES, выбранного владельцем как публичный статус-бейдж. NULL — не выбран. Не FK на список бейджей в коде (он живёт в статике, не в БД) — но см. FK ниже на факт того, что бейдж реально заработан.';

-- Композитный внешний ключ на (user_id, badge_id) в achievements —
-- возможен именно благодаря уже существующему UNIQUE(user_id, badge_id)
-- там (FK на составной ключ требует уникального ограничения на те же
-- колонки у цели). Даёт гарантию на уровне БД, а не только в клиентском
-- коде (который лишь показывает в пикере одни заработанные бейджи, но
-- сам по себе не мешает прямому вызову API выставить чужой/незаработанный
-- id): equipped_badge_id, если не NULL, обязан совпадать с реально
-- записанной строкой achievements этого же пользователя. NULL проходит
-- ограничение всегда (MATCH SIMPLE, поведение Postgres по умолчанию) —
-- снять статус-бейдж можно в любой момент без каких-либо условий.
ALTER TABLE profiles
  ADD CONSTRAINT profiles_equipped_badge_fk
  FOREIGN KEY (id, equipped_badge_id)
  REFERENCES achievements(user_id, badge_id)
  ON DELETE SET NULL;
