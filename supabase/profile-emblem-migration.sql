-- Хранит id пресета из lib/profile-emblems.ts (например "bug",
-- "terminal") или NULL, если пользователь эмблему не выбрал — тогда
-- аватарка остаётся прежней: цветной кружок с инициалом. Отдельной
-- проверки "такой id существует в списке пресетов" в БД нет — тот же
-- принцип, что уже у banner_gradient и avatar_color, список пресетов
-- живёт только в коде, не дублируется в БД constraint'ом.
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS avatar_emblem text;

