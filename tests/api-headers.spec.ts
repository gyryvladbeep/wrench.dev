import { test, expect } from "@playwright/test";

/**
 * ═══════════════════════════════════════════════════════════════
 * УРОВЕНЬ 4 — API ТЕСТИРОВАНИЕ (БЕЗ БРАУЗЕРА)
 * ═══════════════════════════════════════════════════════════════
 *
 * До сих пор мы тестировали через браузер: page.goto(), page.click().
 * Это называется E2E (End-to-End) тестирование — проверяем весь путь
 * пользователя, включая интерфейс.
 *
 * Но у Playwright есть ВТОРОЙ режим — "request" — отправляет HTTP-запросы
 * НАПРЯМУЮ на сервер, без открытия браузера вообще. Это называется
 * API-тестирование, и оно в разы быстрее (не нужно рендерить страницу),
 * а также позволяет проверить логику сервера отдельно от интерфейса.
 *
 * КОГДА ИСПОЛЬЗОВАТЬ ЧТО:
 * ─────────────────────────
 * • E2E (page.goto, click)  — проверяем что видит и делает ПОЛЬЗОВАТЕЛЬ
 * • API (request.post)      — проверяем логику СЕРВЕРА напрямую:
 *   валидацию, коды ответов, обработку ошибок, безопасность
 *
 * В реальной работе хороший тестовый набор использует ОБА подхода:
 * немного E2E тестов на критичные пути пользователя + много API тестов
 * на все варианты входных данных (это быстрее гонять и легче поддерживать).
 *
 * Мы тестируем эндпоинт /api/headers — он делает запрос на переданный
 * URL и возвращает его HTTP-заголовки. У него есть реальная логика:
 * - проверка что передан валидный URL
 * - защита от SSRF (Server-Side Request Forgery) — блокировка запросов
 *   на внутренние адреса (localhost, 127.0.0.1 и т.д.), иначе с сервера
 *   можно было бы просканировать внутреннюю сеть компании
 */

test.describe("API: /api/headers", () => {

  // Обрати внимание — у test() здесь другой набор параметров:
  // не { page }, а { request }. Это специальный объект Playwright
  // именно для прямых HTTP-запросов.

  test("возвращает 400 если URL не передан вообще", async ({ request }) => {
    const response = await request.post("/api/headers", {
      data: {}, // пустое тело запроса — URL отсутствует
    });

    // Проверяем HTTP статус-код ответа
    expect(response.status()).toBe(400);

    // Читаем тело ответа как JSON и проверяем его содержимое
    const body = await response.json();
    expect(body.error).toBeTruthy();
  });

  test("возвращает 400 для невалидного URL (не начинается с http)", async ({ request }) => {
    const response = await request.post("/api/headers", {
      data: { url: "не-похоже-на-урл-вообще" },
    });

    expect(response.status()).toBe(400);
  });

  // ─────────────────────────────────────────────────────────────
  // ПАРАМЕТРИЗОВАННЫЙ ТЕСТ БЕЗОПАСНОСТИ (SSRF защита)
  // ─────────────────────────────────────────────────────────────
  // Это именно то что реальный QA automation engineer тестирует
  // на бэкенде: список "запрещённых" адресов, которые НЕ должны
  // пройти проверку, потому что иначе злоумышленник мог бы заставить
  // сервер сходить во внутреннюю сеть компании.
  const blockedHosts = [
    "http://localhost:3000",
    "http://127.0.0.1",
    "http://0.0.0.0",
    "http://10.0.0.1",        // приватная сеть класса A
    "http://192.168.1.1",     // приватная сеть класса C (домашние роутеры)
    "http://169.254.169.254", // AWS/Cloud metadata endpoint — известная SSRF цель!
  ];

  for (const blockedUrl of blockedHosts) {
    test(`блокирует внутренний адрес: ${blockedUrl}`, async ({ request }) => {
      const response = await request.post("/api/headers", {
        data: { url: blockedUrl },
      });

      // Сервер должен ОТКАЗАТЬ — статус 400, а не попытаться
      // реально сходить на этот адрес
      expect(response.status()).toBe(400);

      const body = await response.json();
      expect(body.error).toContain("can't be inspected");
    });
  }

  test("успешно возвращает заголовки для реального публичного сайта", async ({ request }) => {
    const response = await request.post("/api/headers", {
      data: { url: "https://example.com" },
    });

    expect(response.status()).toBe(200);

    const body = await response.json();

    // Проверяем структуру ответа — что в нём есть нужные поля
    expect(body.status).toBe(200);
    expect(body.headers).toBeTruthy();

    // Проверяем что headers — это объект (а не строка/массив/null)
    expect(typeof body.headers).toBe("object");

    // У любого нормального HTTP-ответа есть заголовок content-type
    expect(body.headers["content-type"]).toBeTruthy();
  });

  test("метод GET на этот эндпоинт не поддерживается", async ({ request }) => {
    // ─────────────────────────────────────────────────────────
    // УРОК: тестируем не только "счастливый путь", но и то что
    // API правильно ОТКАЗЫВАЕТ в неподдерживаемых случаях.
    // Эндпоинт написан только под POST — GET должен вернуть ошибку,
    // а не упасть с невнятным 500 Internal Server Error.
    // ─────────────────────────────────────────────────────────
    const response = await request.get("/api/headers");

    // Next.js по умолчанию возвращает 405 Method Not Allowed
    // для методов, не описанных в route.ts
    expect(response.status()).toBe(405);
  });

});